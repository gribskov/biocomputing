import pandas as pd

# ======================================================================================================================
# main
# ======================================================================================================================
if __name__ == '__main__':
    # Read CSV with pandas and instantly convert to a NumPy array
    kmerfname='data/sbg_all.kmer_100000.txt'
    count_min = 5
    data = pd.read_csv(kmerfname,sep='\t').to_numpy()
    data = data[data[:, 1] > count_min-1]
    data = data[data[:, 1].argsort()]
    print(data.shape)
    print(data)


    exit(0)
